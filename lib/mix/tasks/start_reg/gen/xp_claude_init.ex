defmodule Mix.Tasks.StartReg.Gen.XpClaudeInit do
  @shortdoc "Run Claude init"
  @moduledoc """
  Run Claude init

  Runs Claude Code headlessly (`claude -p "/init"`) to generate a CLAUDE.md
  for the project. Requires the `claude` executable on the PATH.

  References:

  - https://docs.anthropic.com/en/docs/claude-code/cli-reference
  - https://docs.anthropic.com/en/docs/claude-code/memory
  """

  use Igniter.Mix.Task

  @claude_file "CLAUDE.md"

  @impl Igniter.Mix.Task
  def igniter(igniter) do
    case System.find_executable("claude") do
      nil -> Igniter.add_issue(igniter, "`claude` executable not found on PATH")
      claude -> run_init(igniter, claude)
    end
  end

  # Claude writes CLAUDE.md to disk itself, outside of Igniter's rewrite, so
  # `acceptEdits` is needed to let it create the file without prompting.
  # Changes still pending in the igniter are not on disk yet, so Claude will
  # not see them.
  defp run_init(igniter, claude) do
    Mix.shell().info("Running `claude -p /init` (this may take a minute)...")

    case System.cmd(claude, ["-p", "/init", "--permission-mode", "acceptEdits"],
           stderr_to_stdout: true
         ) do
      {_output, 0} ->
        Igniter.add_notice(igniter, "#{@claude_file} generated by `claude /init`")

      {output, status} ->
        Igniter.add_issue(igniter, "`claude -p /init` failed (exit #{status}):\n#{output}")
    end
  end
end
